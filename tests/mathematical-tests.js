const assert=require('node:assert/strict');
const M=require('../src/mathematical-engine.js');
const close=(a,b,t=1e-8)=>assert.ok(Math.abs(a-b)<t,`${a} != ${b}`);

assert.equal(M.parseNumber('3/4').value,.75);
assert.equal(M.parseNumber('0.5000000001').ok,true);
assert.equal(M.parseNumber('Infinity').ok,false);
assert.equal(M.parseNumber('NaN').ok,false);
assert.equal(M.parseNumber('1,2').ok,false);
assert.equal(M.evaluateExpression('3*4-2').value,10);
assert.equal(M.checkNumber('(1+2)/3',1).ok,true);
assert.equal(M.evaluateExpression('globalThis.alert(1)').ok,false);
assert.equal(M.checkNumber('2 acute',2).ok,false);
assert.equal(M.checkNumber('2/3',2/3).ok,true);
assert.equal(M.checkVector('1,2,3',[1,2]).ok,false);
assert.equal(M.checkVector('1,3',[1,2]).ok,false);
assert.equal(M.checkVector('(1, 2)',[1,2]).ok,true);
assert.equal(M.checkMatrix('1,2;3,4',[[1,2],[3,4]]).ok,true);
assert.equal(M.checkMatrix('1,2;3,5',[[1,2],[3,4]]).ok,false);
assert.equal(M.checkMatrix('1,2,3;4,5,6',[[1,2],[3,4]]).ok,false);
assert.equal(M.validateDaily('12 is acute').ok,false);
assert.equal(M.validateDaily('2; acute').ok,true);
assert.equal(M.validateDaily('2; obtuse').ok,false);

assert.deepEqual(M.vectorAdd([1,2],[3,4]),[4,6]);
assert.deepEqual(M.scalarMultiply(3,[1,-2]),[3,-6]);
assert.deepEqual(M.transpose([[1,2,3],[4,5,6]]),[[1,4],[2,5],[3,6]]);
assert.deepEqual(M.matrixMultiply([[1,2],[3,4]],[[2,0],[1,2]]),[[4,4],[10,8]]);
assert.throws(()=>M.matrixMultiply([[1,2]],[[1,2]]),/dimensions/);
close(M.determinant([[4,7],[2,6]]),10);
const inv=M.inverse([[4,7],[2,6]]);close(inv[0][0],.6);close(inv[0][1],-.7);close(inv[1][0],-.2);close(inv[1][1],.4);
assert.throws(()=>M.inverse([[1,2],[2,4]]),/singular/);
assert.deepEqual(M.solve([[2,1],[1,3]],[1,2]).map(x=>+x.toFixed(8)),[.2,.6]);
assert.equal(M.rank([[1,2,3],[2,4,6]]),1);
assert.equal(M.rank([[1,0],[0,1]]),2);

const eig=M.eigenSymmetric2([[2,1],[1,2]]);assert.deepEqual(eig.values,[3,1]);
eig.vectors.forEach((v,i)=>{const Av=[2*v[0]+v[1],v[0]+2*v[1]];close(Av[0],eig.values[i]*v[0]);close(Av[1],eig.values[i]*v[1]);close(Math.hypot(...v),1)});
assert.throws(()=>M.gramSchmidt([[1,2],[2,4]]),/dependent/);
const gs=M.gramSchmidt([[1,1],[1,-1]]);close(gs[0][0]*gs[1][0]+gs[0][1]*gs[1][1],0);
assert.deepEqual(M.leastSquares([[1,0],[1,1],[1,2]],[1,3,5]).map(x=>+x.toFixed(8)),[1,2]);
assert.throws(()=>M.leastSquares([[1,1],[2,2]],[1,2]),/rank/);
const C=M.covariance([[1,2],[2,4],[3,6]]);assert.deepEqual(C,[[1,2],[2,4]]);
assert.deepEqual(M.correlationMatrix([[1,2],[2,4],[3,6]]),[[1,1],[1,1]]);
const pca=M.pca2([[-1,-2],[0,0],[1,2]]);close(pca.values[0],5);close(pca.explainedVariance[0],1);
const s=M.svd2([[3,0],[0,2]]);assert.deepEqual(s.singularValues,[3,2]);
const A0=[[1,2],[3,4]],sv=M.svd2(A0);for(let i=0;i<2;i++)for(let j=0;j<2;j++)close(sv.singularValues.reduce((sum,x,k)=>sum+sv.U[k][i]*x*sv.V[k][j],0),A0[i][j]);
assert.equal(M.alleleFrequency([0,1,2,1]),.5);
assert.deepEqual(M.genotypeFrequencies([0,1,1,2]),[.25,.5,.25]);
assert.deepEqual(M.hardyWeinberg(.5),[.25,.5,.25]);
assert.equal(M.effectivePopulationSize(10,10),20);
assert.deepEqual(M.drift(.5,2,2,()=>.1),[.5,1,1]);

const eigenProblem={id:'P3-0',statement:'A=diag(2,-1)',answer:'2,-1'};
assert.equal(M.validateGenerated(eigenProblem,'2;1,0;-1;0,1').ok,true);
assert.equal(M.validateGenerated(eigenProblem,'2;1,0;-1;0,0').ok,false);
assert.equal(M.validateGenerated(eigenProblem,'2;2,0;-1;0,1').ok,false);
assert.equal(M.validateGenerated(eigenProblem,'2;1,0').ok,false);
assert.equal(M.checkEigenpairs('2;1,0;-1;0,1',[[2,0],[0,-1]],[2,-1],2).components.filter(x=>x.ok).length,6);
console.log('PASS: mathematical validators, linear algebra, PCA/SVD 2×2 routines, and population-genetics calculations.');
